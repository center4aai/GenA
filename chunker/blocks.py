"""Общий словарь типов блоков прозы (учебники, энциклопедии).

Один список на все пути чанкинга: детерминированный (`main.py`,
layout-извлечение PDF) и будущий LLM-чанкер. Тип блока уезжает в
``fragment_data.block_type`` чанка, а по нему гейт и генератор получают
подсказку («врезка», «подпись к иллюстрации»).
"""

from __future__ import annotations

# Типы, из которых делаются чанки.
KEPT_BLOCK_TYPES = frozenset({"body", "list", "inset", "caption", "glossary_entry"})

# Типы, которые выбрасываются ещё в чанкере (только счётчики в статистике).
DROPPED_BLOCK_TYPES = frozenset({
    "exercise",      # вопросы и задания к параграфу, поручения «Выясните…»
    "front_matter",  # титул, выходные данные, введение, оглавление, сокращения
    "toc",           # оглавление, распознанное структурно
    "imprint",       # выходные данные, распознанные структурно
    "abbreviations", # список сокращений / условные обозначения
    "caption_short", # подпись к иллюстрации в одно предложение
    "inset_short",   # врезка короче 80 символов — подпись без факта
    "figure_text",   # текст внутри схем/таблиц/картинок
    "debris",        # огрызки вёрстки
    "junk",          # колонтитулы, номера страниц, типографские метки
    "table",         # таблица/схема, распавшаяся на строки (метод llm)
})

BLOCK_TYPES = KEPT_BLOCK_TYPES | DROPPED_BLOCK_TYPES

# Подписи для промптов (гейт/генератор) — только для сохраняемых типов.
BLOCK_TYPE_LABELS_RU = {
    "body": "основной текст",
    "list": "основной текст (перечень)",
    "inset": "врезка",
    "caption": "подпись к иллюстрации",
    "glossary_entry": "словарная статья",
}
